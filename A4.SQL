SET SERVEROUTPUT ON;

DECLARE

ROLL_NO NUMBER:=1;
BOOK_NAME VARCHAR2(20):='DBMS';
DAYS NUMBER:=35;
FINE NUMBER:=0;

BEGIN

IF DAYS>15 AND DAYS<=30 THEN

FINE:=DAYS*5;

ELSIF DAYS>30 THEN

FINE:=DAYS*50;

ELSE

FINE:=0;

END IF;

DBMS_OUTPUT.PUT_LINE('ROLL NO = ' || ROLL_NO);

DBMS_OUTPUT.PUT_LINE('BOOK NAME = ' || BOOK_NAME);

DBMS_OUTPUT.PUT_LINE('TOTAL DAYS = ' || DAYS);

DBMS_OUTPUT.PUT_LINE('FINE AMOUNT = ' || FINE);

EXCEPTION

WHEN OTHERS THEN

DBMS_OUTPUT.PUT_LINE('ERROR');

END;
/